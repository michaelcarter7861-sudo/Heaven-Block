import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const resRoot = path.join(root, 'android', 'app', 'src', 'main', 'res');
const foregroundPath = path.join(root, 'assets', 'icon-foreground.svg');
const manifestPath = path.join(root, 'android', 'app', 'src', 'main', 'AndroidManifest.xml');
await fs.access(manifestPath);
await fs.access(foregroundPath);
const foreground = await fs.readFile(foregroundPath);
const densities = [['mdpi',108],['hdpi',162],['xhdpi',216],['xxhdpi',324],['xxxhdpi',432]];
for (const [density,size] of densities) {
  const dir = path.join(resRoot, 'drawable-' + density);
  await fs.mkdir(dir,{recursive:true});
  await sharp(foreground).resize(size,size,{fit:'contain'}).png({compressionLevel:9}).toFile(path.join(dir,'ic_launcher_foreground.png'));
}
const adaptive = '<?xml version="1.0" encoding="utf-8"?>\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n    <background android:drawable="@color/ic_launcher_background"/>\n    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n</adaptive-icon>\n';
const items = [
  [path.join(resRoot,'values','ic_launcher_background.xml'), '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n  <color name="ic_launcher_background">#0B2418</color>\n</resources>\n'],
  [path.join(resRoot,'mipmap-anydpi-v26','ic_launcher.xml'), adaptive],
  [path.join(resRoot,'mipmap-anydpi-v26','ic_launcher_round.xml'), adaptive],
];
for (const [file,content] of items) { await fs.mkdir(path.dirname(file),{recursive:true}); await fs.writeFile(file,content,'utf8'); }
console.log('Applied HeavenBlocks adaptive Android launcher icon.');
console.log('Legacy mipmap icons and native splash images are generated by @capacitor/assets.');
